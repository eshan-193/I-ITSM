-- I-ITSM schema. Works on PostgreSQL and on H2 in PostgreSQL mode (used for tests).

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)   NOT NULL UNIQUE,
    name        VARCHAR(80)   NOT NULL,
    description VARCHAR(500),
    keywords    VARCHAR(1000),
    active      BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Single-table inheritance: one row per user, "role" says which subclass.
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                 VARCHAR(20)  NOT NULL,
    name                 VARCHAR(100) NOT NULL,
    email                VARCHAR(120) NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    phone                VARCHAR(30),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP    NOT NULL,
    department           VARCHAR(80),
    job_title            VARCHAR(80),
    max_active_incidents INTEGER,
    available            BOOLEAN,
    team_lead            BOOLEAN,
    experience_years     INTEGER,
    CONSTRAINT chk_users_role CHECK (role IN ('EMPLOYEE', 'TECHNICIAN', 'ADMIN'))
);

CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id   BIGINT NOT NULL REFERENCES categories (id),
    PRIMARY KEY (technician_id, category_id)
);

CREATE TABLE it_services (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL UNIQUE,
    description         VARCHAR(500),
    criticality         VARCHAR(20)  NOT NULL,
    default_category_id BIGINT REFERENCES categories (id),
    active              BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Directed dependency graph between services ("Payments depends on Database").
CREATE TABLE service_dependencies (
    service_id    BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    depends_on_id BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    PRIMARY KEY (service_id, depends_on_id),
    CONSTRAINT chk_no_self_dependency CHECK (service_id <> depends_on_id)
);

-- service_id NULL = organisation-wide default policy for that priority.
CREATE TABLE sla_policies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority           VARCHAR(5) NOT NULL,
    service_id         BIGINT REFERENCES it_services (id) ON DELETE CASCADE,
    response_minutes   INTEGER    NOT NULL CHECK (response_minutes > 0),
    resolution_minutes INTEGER    NOT NULL CHECK (resolution_minutes > 0),
    CONSTRAINT uq_sla_priority_service UNIQUE (priority, service_id)
);

CREATE TABLE incidents (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version                   BIGINT        NOT NULL DEFAULT 0,
    title                     VARCHAR(150)  NOT NULL,
    description               VARCHAR(4000) NOT NULL,
    category_id               BIGINT REFERENCES categories (id),
    classification_source     VARCHAR(20),
    classification_confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
    service_id                BIGINT        NOT NULL REFERENCES it_services (id),
    impact                    VARCHAR(10)   NOT NULL,
    urgency                   VARCHAR(10)   NOT NULL,
    affected_users            INTEGER       NOT NULL CHECK (affected_users >= 1),
    priority                  VARCHAR(5),
    priority_score            INTEGER       NOT NULL DEFAULT 0,
    priority_rationale        VARCHAR(500),
    status                    VARCHAR(20)   NOT NULL,
    reporter_id               BIGINT        NOT NULL REFERENCES users (id),
    assignee_id               BIGINT REFERENCES users (id),
    escalation_level          INTEGER       NOT NULL DEFAULT 0,
    escalated_at              TIMESTAMP,
    -- embedded SLA tracker (composition: same row)
    sla_started_at            TIMESTAMP,
    response_deadline         TIMESTAMP,
    resolution_deadline       TIMESTAMP,
    responded_at              TIMESTAMP,
    sla_resolved_at           TIMESTAMP,
    response_breached         BOOLEAN       NOT NULL DEFAULT FALSE,
    resolution_breached       BOOLEAN       NOT NULL DEFAULT FALSE,
    sla_warning_sent          BOOLEAN       NOT NULL DEFAULT FALSE,
    paused_since              TIMESTAMP,
    paused_minutes            BIGINT        NOT NULL DEFAULT 0,
    -- lifecycle timestamps
    created_at                TIMESTAMP     NOT NULL,
    updated_at                TIMESTAMP     NOT NULL,
    assigned_at               TIMESTAMP,
    acknowledged_at           TIMESTAMP,
    resolved_at               TIMESTAMP,
    closed_at                 TIMESTAMP,
    -- resolution and closure
    resolution                VARCHAR(4000),
    root_cause                VARCHAR(1000),
    closure_note              VARCHAR(1000),
    feedback_rating           INTEGER CHECK (feedback_rating BETWEEN 1 AND 5),
    feedback_comment          VARCHAR(1000),
    reopen_count              INTEGER       NOT NULL DEFAULT 0,
    duplicate_of_id           BIGINT REFERENCES incidents (id)
);

CREATE INDEX idx_incidents_status ON incidents (status);
CREATE INDEX idx_incidents_priority ON incidents (priority);
CREATE INDEX idx_incidents_created ON incidents (created_at);
CREATE INDEX idx_incidents_assignee ON incidents (assignee_id);
CREATE INDEX idx_incidents_service ON incidents (service_id);
CREATE INDEX idx_incidents_reporter ON incidents (reporter_id);

CREATE TABLE incident_watchers (
    incident_id BIGINT NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    PRIMARY KEY (incident_id, user_id)
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id   BIGINT        NOT NULL REFERENCES users (id),
    text        VARCHAR(4000) NOT NULL,
    type        VARCHAR(30)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL
);
CREATE INDEX idx_comments_incident ON comments (incident_id);

CREATE TABLE audit_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    actor_id    BIGINT REFERENCES users (id),
    actor_name  VARCHAR(120) NOT NULL,
    timestamp   TIMESTAMP    NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    from_status VARCHAR(20),
    to_status   VARCHAR(20),
    description VARCHAR(1000)
);
CREATE INDEX idx_audit_incident ON audit_entries (incident_id);
CREATE INDEX idx_audit_timestamp ON audit_entries (timestamp);

CREATE TABLE sla_violations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id   BIGINT      NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    breach_type   VARCHAR(20) NOT NULL,
    priority      VARCHAR(5)  NOT NULL,
    technician_id BIGINT REFERENCES users (id),
    deadline      TIMESTAMP   NOT NULL,
    detected_at   TIMESTAMP   NOT NULL
);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    incident_id  BIGINT REFERENCES incidents (id) ON DELETE CASCADE,
    message      VARCHAR(500) NOT NULL,
    severity     VARCHAR(10)  NOT NULL,
    is_read      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_notifications_recipient ON notifications (recipient_id, is_read);

CREATE TABLE outbound_messages (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel           VARCHAR(10)   NOT NULL,
    recipient_address VARCHAR(120)  NOT NULL,
    subject           VARCHAR(200),
    body              VARCHAR(2000) NOT NULL,
    status            VARCHAR(10)   NOT NULL,
    error_message     VARCHAR(500),
    created_at        TIMESTAMP     NOT NULL
);

CREATE TABLE system_settings (
    setting_key   VARCHAR(60)  PRIMARY KEY,
    setting_value VARCHAR(200) NOT NULL
);
